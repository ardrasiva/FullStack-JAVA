package com.example.restaurant.Model;

public class Restaurant {
    private String name;
    private float price;

    public String getName(){
        return name;
    }
    public float getPrice(){
        return price;
    }

    public void setName(String n){
        this.name = n;
    }
    public void setPrice(float p){
        this.price = p;
    }
    
}
